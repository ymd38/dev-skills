    if (cd "$TARGET" && npx --yes skills add ymd38/dev-skills --skill '*' --agent claude-code -y --copy); then
      ST_SKILLS="installed via npx skills add"
    else
      ST_SKILLS="FAILED — run manually: npx skills add ymd38/dev-skills --skill '*' --agent claude-code -y --copy"
    fi
  else
    ST_SKILLS="SKIPPED — npx not found; run manually: npx skills add ymd38/dev-skills --skill '*' --agent claude-code -y --copy"
  fi
fi

# ── Branch protection (required status checks) ──
# A CI check only gates merges once branch protection marks it required.
ST_PROTECT="skipped (no CI generated)"
if [[ "$CI_GENERATED" == "1" ]]; then
  if ! command -v gh >/dev/null 2>&1; then
    ST_PROTECT="unknown (gh CLI not found — set required checks in GitHub settings)"
  elif ! git -C "$TARGET" remote get-url origin >/dev/null 2>&1; then
    ST_PROTECT="NOT CONFIGURED (no git remote yet — after the first push, re-run with --protect)"
  else
    repo_slug="$(cd "$TARGET" && gh repo view --json nameWithOwner -q .nameWithOwner 2>/dev/null || true)"
    if [[ -z "$repo_slug" ]]; then
      ST_PROTECT="unknown (gh cannot resolve the repository — check gh auth status)"
    elif [[ "$PROTECT" == "1" ]]; then
      contexts=""
      has_lang go && contexts="${contexts:+$contexts,}\"Go (build, test, lint)\""
      [[ "$HAS_NODE" == "1" ]] && contexts="${contexts:+$contexts,}\"Node (lint, typecheck, test)\""
      has_lang python && contexts="${contexts:+$contexts,}\"Python (lint, test)\""
      contexts="${contexts:+$contexts,}\"Secret Scan (Gitleaks)\",\"SAST (Semgrep)\""
      [[ -n "$NODE_AUDIT_JOB" ]] && contexts="$contexts,\"Node Dependency Audit\""
      payload="$(mktemp)"
      printf '{"required_status_checks":{"strict":true,"contexts":[%s]},"enforce_admins":true,"required_pull_request_reviews":null,"restrictions":null,"allow_force_pushes":false,"allow_deletions":false}\n' "$contexts" >"$payload"
      if (cd "$TARGET" && gh api -X PUT "repos/$repo_slug/branches/$BRANCH/protection" --input "$payload" >/dev/null 2>&1); then
        ST_PROTECT="applied (required checks incl. Gitleaks / Semgrep on $BRANCH)"
      else
        ST_PROTECT="FAILED — branch protection requires REPOSITORY ADMIN. Verify: (1) gh auth status shows an account with admin on this repo (a 403 means the token lacks admin), (2) the $BRANCH branch is pushed. Then re-run with --protect, or set required checks manually in GitHub settings"
      fi
      rm -f "$payload"
    else
      if (cd "$TARGET" && gh api "repos/$repo_slug/branches/$BRANCH/protection" >/dev/null 2>&1); then
        ST_PROTECT="configured on $BRANCH"
      else
        ST_PROTECT="NOT CONFIGURED — re-run with --protect, or set required checks in GitHub settings"
      fi
    fi
  fi
fi

